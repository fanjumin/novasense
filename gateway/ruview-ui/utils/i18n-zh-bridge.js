const SKIP_TAGS = new Set([
  'SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA', 'CODE', 'PRE',
  'CANVAS', 'SVG', 'MATH', 'KBD'
]);
const I18N_ATTRS = ['data-i18n', 'data-i18n-placeholder', 'data-i18n-aria'];
const TRANSLATABLE_ATTRS = ['title', 'placeholder', 'aria-label', 'alt'];

const originals = new WeakMap();      // Text node -> original nodeValue
const attrOriginals = new WeakMap();  // Element -> { attr: originalValue }
let observer = null;
let rafPending = false;
let installed = false;

let activeEntry = null; // { dict, rules } for the current locale (null = English)

function activeDict() {
  if (i18n.locale === 'zh') return { dict: UI_ZH, rules: RULES };
  if (i18n.locale === 'pl') return { dict: UI_PL, rules: RULES_PL };
  return null;
}

function lookup(text) {
  if (!text || !activeEntry) return null;
  const hit = activeEntry.dict[text];
  if (hit && hit !== text) return hit;
  for (const [re, rep] of activeEntry.rules) {
    if (re.test(text)) return text.replace(re, rep);
  }
  return null;
}

function shouldSkip(el) {
  if (!el || el.nodeType !== 1) return true;
  if (SKIP_TAGS.has(el.tagName)) return true;
  for (const a of I18N_ATTRS) {
    if (el.hasAttribute(a)) return true;
  }
  return false;
}

function translateTextNodes(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(n) {
      const p = n.parentElement;
      if (!p || shouldSkip(p)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  let node;
  while ((node = walker.nextNode())) {
    // Look up the ORIGINAL (pre-translation) value so a node already
    // translated for another locale (e.g. zh → pl) re-resolves correctly.
    const raw = originals.get(node) ?? node.nodeValue;
    const trimmed = raw.trim();
    if (!trimmed) continue;
    const hit = lookup(trimmed);
    if (!hit) continue;
    if (!originals.has(node)) originals.set(node, raw);
    // Preserve surrounding whitespace of the original node.
    const lead = raw.slice(0, raw.indexOf(trimmed));
    const trail = raw.slice(raw.indexOf(trimmed) + trimmed.length);
    node.nodeValue = lead + hit + trail;
  }
}

function translateAttrs(root) {
  const scope = (root === document || root === document.body)
    ? document.querySelectorAll('[title],[placeholder],[aria-label],[alt]')
    : root.querySelectorAll('[title],[placeholder],[aria-label],[alt]');
  scope.forEach(el => {
    if (shouldSkip(el)) return;
    for (const attr of TRANSLATABLE_ATTRS) {
      const v = el.getAttribute(attr);
      if (!v) continue;
      const hit = lookup(v.trim());
      if (!hit) continue;
      const store = attrOriginals.get(el) || {};
      if (!(attr in store)) {
        store[attr] = v;
        attrOriginals.set(el, store);
      }
      el.setAttribute(attr, hit);
    }
  });
}

function restoreTextNodes(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(n) {
      return (n.parentElement && originals.has(n))
        ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  let node;
  while ((node = walker.nextNode())) {
    node.nodeValue = originals.get(node);
    originals.delete(node);
  }
}

function restoreAttrs(root) {
  const scope = (root === document || root === document.body)
    ? document.querySelectorAll('[title],[placeholder],[aria-label],[alt]')
    : root.querySelectorAll('[title],[placeholder],[aria-label],[alt]');
  scope.forEach(el => {
    const store = attrOriginals.get(el);
    if (!store) return;
    for (const attr of Object.keys(store)) {
      el.setAttribute(attr, store[attr]);
    }
    attrOriginals.delete(el);
  });
}

function applyAll() {
  activeEntry = activeDict();
  if (activeEntry) {
    translateTextNodes(document.body);
    translateAttrs(document.body);
  } else {
    restoreTextNodes(document.body);
    restoreAttrs(document.body);
  }
}

function scheduleApply() {
  if (rafPending) return;
  rafPending = true;
  requestAnimationFrame(() => {
    rafPending = false;
    if (!activeDict()) return; // nothing to do while English
    applyAll();
  });
}

function refresh() {
  if (!installed) return;
  applyAll();
}

/**
 * Install the runtime text bridge. Idempotent.
 * Call once after `i18n.init()` (app.js, pose-fusion/js/main.js, viz.html).
 */
export function installZhBridge() {
  if (installed) return;
  installed = true;

  // Re-apply (or restore) whenever the locale changes.
  const origSetLocale = i18n.setLocale.bind(i18n);
  i18n.setLocale = function patchedSetLocale(locale) {
    origSetLocale(locale);
    refresh();
  };

  // Cover content rendered after initial load (components, toasts, HUD...).
  if (typeof MutationObserver !== 'undefined' && document.body) {
    observer = new MutationObserver(muts => {
      if (!activeDict()) return;
      for (const m of muts) {
        if (m.type === 'childList') {
          m.addedNodes.forEach(n => {
            if (n.nodeType === 1) {
              if (shouldSkip(n)) return;
              translateTextNodes(n);
              translateAttrs(n);
            } else if (n.nodeType === 3 && n.parentElement && !shouldSkip(n.parentElement)) {
              scheduleApply();
            }
          });
        } else if (m.type === 'characterData' && m.target.parentElement) {
          scheduleApply();
        } else if (m.type === 'attributes') {
          scheduleApply();
        }
      }
    });
    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
      attributeFilter: TRANSLATABLE_ATTRS
    });
  }

  // Initial pass for content already in the DOM (components render before init).
  if (activeDict()) applyAll();
}

/**
 * Install the runtime text bridge for all non-English locales (zh, pl).
 * Alias of installZhBridge — use this name going forward.
 */
export function installTextBridge() {
  installZhBridge();
}
